// Allocate a free bus instance (I2C, SPI, UART) enabled in the devicetree,
// route it to the requested pins at runtime and hand the Zephyr device to the
// caller. Per-board tables of allocatable instances are provided by the
// application (the CircuitPython build generates them from the board's
// devicetree; see modules/iobroker/README.md for the contract).
//
// Runtime routing works on nRF SoCs because their pin control encoding is a
// simple bit-packed value (see zephyr/dt-bindings/pinctrl/nrf-pinctrl.h and
// soc/nordic/common/pinctrl_soc.h) that can be computed at runtime, and any
// peripheral function can be routed to (almost) any pin via PSEL.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include <zephyr/device.h>
#include <zephyr/drivers/gpio.h>

// Runtime bus routing lets the module re-route a bus instance's pins at
// runtime. It is available when Zephyr is built with dynamic pinctrl states and
// device de-init support. Without it the bus allocate/release functions report
// -ENOSYS and the bus instance tables are not used.
#if defined(CONFIG_PINCTRL_NRF) && defined(CONFIG_PINCTRL_DYNAMIC) && \
    defined(CONFIG_DEVICE_DEINIT_SUPPORT)
#define IOBROKER_ROUTING 1
#else
#define IOBROKER_ROUTING 0
#endif

// ADC pad allocation is available when a supported ADC device is built: the
// nRF SAADC driver (src/nordic/nrf/), the NXP MCX N LPADC
// (src/nxp/mcxn/) or the emulated ADC (src/emul/, native_sim). Without it
// the allocate function reports -ENOSYS.
#if defined(CONFIG_ADC_NRFX_SAADC) || defined(CONFIG_ADC_EMUL) || \
    defined(CONFIG_ADC_MCUX_LPADC)
#define IOBROKER_ADC 1
#else
#define IOBROKER_ADC 0
#endif

// DAC pad allocation is available when a supported DAC device is built: the
// Renesas RA DAC (src/renesas/ra/), the NXP MCX N LPDAC (src/nxp/mcxn/) or
// the emulated test DAC (src/emul/, native_sim). Without it the allocate
// function reports -ENOSYS.
#if defined(CONFIG_DAC_TEST) || defined(CONFIG_DAC_RENESAS_RA) || \
    defined(CONFIG_DAC_MCUX_LPDAC)
#define IOBROKER_DAC 1
#else
#define IOBROKER_DAC 0
#endif

// Signals needed by the widest bus (UART with tx/rx/rts/cts).
#define IOBROKER_MAX_PINS 4

// Package pin that leaves a signal disconnected (only valid for optional
// signals such as UART rts/cts).
#define IOBROKER_NO_PIN ((package_pin_t)0xffff)

// Marker for a SoC pad with no GPIO controller (an analog-only pad).
#define IOBROKER_PAD_NO_GPIO ((uint16_t)0xffff)

// A physical pin of the SoC's package, numbered the way the SoC datasheet
// numbers its package pins (1..N for QFN-style packages; BGA-style packages
// use the datasheet's sequential numbering of the balls). Translating a pin
// name from a schematic or board layout to a package pin is a board concern;
// the module only knows the package pin -> SoC pad mapping below.
typedef uint16_t package_pin_t;

// Wrap a datasheet package pin number into a package_pin_t.
#define PACKAGE_PIN(number) ((package_pin_t)(number))

// One entry of the package pin map: a physical package pin and the SoC pad
// it is bonded to. The SoC pad is numbered by the package's pin ids -- balls
// in row-major order for a ball grid (the datasheet only labels them, e.g.
// A17), or the datasheet's pin number for a QFN/QFP package. Pads bonded to
// a GPIO controller carry that bond as their global GPIO number (port index
// * 32 + pin within the port, what the GPIO controller table below
// resolves); analog-only pads, which no GPIO controller covers, have no
// bond and only the analog APIs reach them, through their package pin.
// Package pins that bond neither a GPIO nor an analog function (power, ...)
// are omitted; requesting one fails with -EINVAL.
//
// The map is generated by the module build from the selected IOBROKER_PACKAGE
// choice (see packages/), or as an empty map when no package applies to the
// SoC. With an empty map every package pin lookup fails with -EINVAL.
typedef struct {
    package_pin_t package_pin;
    uint16_t soc_pad;
    // Global GPIO number the pad is bonded to, or IOBROKER_PAD_NO_GPIO when
    // the pad has no GPIO controller (an analog-only pad).
    uint16_t gpio_pad;
} iobroker_package_pin_t;

extern const iobroker_package_pin_t iobroker_package_pins[];
extern const size_t iobroker_package_pin_count;

// GPIO controller table: the board lists every GPIO controller together with
// its hardware port index, which defines the global pin numbering
// (index * 32 + pin). Generated into board.c; boards without GPIO
// controllers generate an empty table, so lookups return -EINVAL.
extern const struct device *const iobroker_gpio_port_devices[];
extern const uint8_t iobroker_gpio_port_indexes[];
// Register block address of each controller, same order; see
// iobroker_instance_t.reg_addr.
extern const uint32_t iobroker_gpio_port_addrs[];
extern const size_t iobroker_gpio_port_count;

// Resolve a global pin number to its GPIO controller device and the pin
// number within that controller (the two values Zephyr's GPIO API takes).
// Returns 0, or -EINVAL when no controller covers the number.
int iobroker_gpio_split(uint16_t number, const struct device **port_out,
    gpio_pin_t *pin_out);

// Map a GPIO controller's hardware port index and the pin number within it
// (the two halves of the global pin numbering: index * 32 + pin) to the
// package pin the pad is bonded to. The inverse of the package pin map's
// soc_pad column. Returns 0, or -EINVAL when the pad has no entry in the
// package pin map.
int iobroker_gpio_package_pin(uint8_t port, gpio_pin_t pin,
    package_pin_t *package_pin_out);

// Resolve a package pin to the global GPIO number of the pad it is bonded to
// (GPIO controller port index * 32 + pin within the port), for a caller that
// drives the pad's registers itself. IOBROKER_NO_PIN passes through
// unchanged. Returns 0, or -EINVAL when the pin is not in the map or its pad
// has no GPIO controller (an analog-only pad); *gpio_pad_out is untouched on
// error.
int iobroker_package_pin_gpio_pad(package_pin_t pin, uint16_t *gpio_pad_out);

#if defined(CONFIG_PINCTRL_NRF)

#include <zephyr/drivers/pinctrl.h>

// Description of one allocatable bus instance. Filled in by the board tables.
typedef struct {
    const struct device *dev;
    // Register block address of the instance, from the devicetree. The SoC
    // routing code uses it to decide which pads the instance can reach: on
    // nRF54L, peripherals only drive pads of their own power domain, which
    // the address encodes.
    uint32_t reg_addr;
    // Pin control configuration of the device. Mutable because
    // CONFIG_PINCTRL_DYNAMIC moves these to RAM so that states can be
    // swapped at runtime.
    struct pinctrl_dev_config *pcfg;
    // Pin control entries of the devicetree "default" state, or NULL when
    // the instance was enabled with disconnected pins so that it can be
    // routed dynamically to any pin.
    const pinctrl_soc_pin_t *dt_psels;
    uint8_t dt_psel_count;
} iobroker_instance_t;

// Runtime bookkeeping for one allocatable bus instance. The arrays live for
// the life of the firmware because Zephyr's pinctrl API keeps pointers to
// them inside the device's pinctrl_dev_config.
typedef struct {
    pinctrl_soc_pin_t default_pins[IOBROKER_MAX_PINS];
    pinctrl_soc_pin_t sleep_pins[IOBROKER_MAX_PINS];
    struct pinctrl_state states[2];
    bool in_use;
    // True when the instance's states were swapped for runtime-built entries.
    bool routed;
    // Package pins the current allocation claims (copies of the request).
    // Used by iobroker_pin_in_use(); empty while the instance is free.
    package_pin_t pins[IOBROKER_MAX_PINS];
    uint8_t pin_count;
} iobroker_state_t;

// Generated board tables, emitted by the board's generated board.c whenever
// the nRF pinctrl driver is built. They are used only when runtime routing is
// available (IOBROKER_ROUTING); boards without it still define them.
extern const iobroker_instance_t iobroker_i2c_buses[];
extern const size_t iobroker_i2c_bus_count;
extern iobroker_state_t iobroker_i2c_bus_states[];

extern const iobroker_instance_t iobroker_spi_buses[];
extern const size_t iobroker_spi_bus_count;
extern iobroker_state_t iobroker_spi_bus_states[];

extern const iobroker_instance_t iobroker_uart_buses[];
extern const size_t iobroker_uart_bus_count;
extern iobroker_state_t iobroker_uart_bus_states[];

// PWM instances. Each nRF PWM instance has four outputs (OUT0..OUT3) that
// are routed with the same pinctrl mechanism as bus signals.
extern const iobroker_instance_t iobroker_pwm_buses[];
extern const size_t iobroker_pwm_bus_count;
extern iobroker_state_t iobroker_pwm_bus_states[];

// SoC pads owned by fixed peripherals (console UART, flash instance, I2S,
// ...): the pads their devicetree pinctrl default state drives at boot.
// iobroker_pin_in_use() reports these as always busy so that allocate()
// rejects requests for them with -EBUSY.
extern const uint16_t iobroker_reserved_pads[];
extern const size_t iobroker_reserved_pads_count;

#endif // CONFIG_PINCTRL_NRF

// The functions below return 0 on success and set *dev_out to the Zephyr
// device of an allocated instance. A negative errno is returned on failure:
//   -ENODEV: no compatible instance is free
//   -ENOSYS: dynamic pin routing is unsupported on this SoC
//   -EBUSY: a requested pin is already claimed by an allocated instance
//   -EINVAL: a pin is not in the package map, has no GPIO, or no instance
//            of this kind can be routed to the requested pins on this SoC
//            (a pin-to-peripheral restriction, not a busy one)
//   other negative values: a routing operation failed
// Optional signals may be disconnected (IOBROKER_NO_PIN). Every allocate
// call must be paired with iobroker_release().
int iobroker_i2c_allocate(package_pin_t sda, package_pin_t scl,
    const struct device **dev_out);
int iobroker_spi_allocate(package_pin_t clock, package_pin_t mosi,
    package_pin_t miso, const struct device **dev_out);
int iobroker_uart_allocate(package_pin_t tx, package_pin_t rx,
    package_pin_t rts, package_pin_t cts, const struct device **dev_out);
// Allocate a whole PWM instance for one output pin, routed to the
// instance's first output (OUT0 on nRF); its other outputs stay
// disconnected. The instance is not shared, so the caller may program all
// of it (neopixel_write plays its own sequence). Like the bus allocate
// functions, the caller initializes the device (device_init()) and returns
// it with iobroker_release(). Sharing an instance between pins with the same
// base frequency, as pwmio will want, is not supported yet.
int iobroker_pwm_allocate(package_pin_t pin, const struct device **dev_out);

// Allocate a package pin for the ADC. Analog inputs have no runtime routing:
// the pad's analog input is fixed by the SoC, so the call resolves and
// returns it in *input_out (the input selector the device's channel
// configuration takes, such as a SAADC AIN number; undefined when the device
// has no selectable inputs, as on the emulated ADC). The call also assigns a
// free channel slot on the ADC device, returned in *channel_out; the caller
// configures the channel itself (adc_channel_setup()) with channel_id =
// *channel_out and input_positive = *input_out where the device takes an
// input selector. The pad stays claimed while the allocation is held, so bus
// allocate() calls and GPIO allocations refuse it with -EBUSY.
//
// Returns 0, or a negative errno:
//   -ENOSYS: no ADC support on this SoC
//   -EINVAL: the pin is disconnected, unknown, or has no analog function
//   -EBUSY:  the pad is already claimed
//   -ENOMEM: the analog claim registry is full
int iobroker_adc_allocate(package_pin_t pin, const struct device **dev_out,
    uint8_t *channel_out, uint8_t *input_out);

// Release an ADC pad allocated with iobroker_adc_allocate(), unconfigure its
// channel if the ADC device needs that (Zephyr's ADC API has no channel
// release, so implementations handle it per SoC) and return the pad to a
// quiescent state. Pass the device and channel the allocate call returned.
// Returns true when an allocation was held.
bool iobroker_adc_release(const struct device *dev, uint8_t channel);

// Allocate a package pin for the DAC and hand out a free channel slot on the
// DAC device. DAC outputs are like ADC inputs fixed per pad: no runtime
// routing, the pad's analog switch is applied by the implementation. The
// caller configures the channel itself (dac_channel_setup()) with channel_id
// = *channel_out and input_positive = *input_out where the device takes an
// input selector. The pad stays claimed while the allocation is held, so bus
// allocate() calls and GPIO allocations refuse it with -EBUSY.
//
// Returns 0, or a negative errno:
//   -ENOSYS: no DAC support on this SoC
//   -EINVAL: the pin is disconnected, unknown, or has no analog function
//   -EBUSY:  the pad is already claimed
//   -ENOMEM: the analog claim registry is full
int iobroker_dac_allocate(package_pin_t pin, const struct device **dev_out,
    uint8_t *channel_out, uint8_t *input_out);

// Release a DAC pad allocated with iobroker_dac_allocate(), unconfigure its
// channel if the DAC device needs that (Zephyr's DAC API has no channel
// release, so implementations handle it per SoC) and return the pad to a
// quiescent state. Pass the device and channel the allocate call returned.
// Returns true when an allocation was held.
bool iobroker_dac_release(const struct device *dev, uint8_t channel);

// Returns true when the package pin is currently claimed by an allocated bus
// instance, a GPIO allocation, or a fixed peripheral (console UART, flash
// instance, ... whose pads are listed in iobroker_reserved_pads). Call this
// before allocate() to find out which requested pin is already in use.
// Disconnected signals (IOBROKER_NO_PIN) and package pins with no SoC pad are
// never in use.
bool iobroker_pin_in_use(package_pin_t pin);

// Allocate a package pin for plain GPIO use. The module only claims it: while
// held, bus allocate() calls and further GPIO allocations fail with -EBUSY.
// The pin is resolved through the package pin map, and both values Zephyr's
// GPIO API needs are returned: *port_out receives the GPIO controller device
// and *pin_out the pin number within it, so that the caller can configure the
// pad itself (gpio_pin_configure()). Returns 0, or a negative errno:
//   -EINVAL: pin is disconnected (IOBROKER_NO_PIN) or has no entry in the
//            package pin map
//   -EBUSY: the pin is already claimed
//   -ENOMEM: the GPIO claim registry is full
int iobroker_gpio_allocate(package_pin_t pin,
    const struct device **port_out, gpio_pin_t *pin_out);

// Release a GPIO claim made with iobroker_gpio_allocate() and return the pad
// to a quiescent state: disconnected from any peripheral routing, input
// buffer and driver off, no pulls (a plain input on SoCs without
// GPIO_DISCONNECTED support). Pass the device and pin number that the
// allocate call returned. Returns true when a claim was held.
bool iobroker_gpio_release(const struct device *port, gpio_pin_t number);

// Release an instance previously returned by one of the allocate functions.
// Returns true when the instance had been dynamically routed, in which case
// the caller is responsible for resetting the pins it had routed to it. The
// device is de-initialized on release, so it is left uninitialized; the
// caller initializes it again when it allocates the instance next.
bool iobroker_release(const struct device *dev);
